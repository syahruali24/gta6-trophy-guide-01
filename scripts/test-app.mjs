import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
const root=fileURLToPath(new URL("../",import.meta.url));
const data=JSON.parse(readFileSync(join(root,"app/data/trophies.json"),"utf8"));
const app=readFileSync(join(root,"app/app.js"),"utf8");
assert.equal(data.trophies.length,55);
assert.equal(new Set(data.trophies.map(t=>t.id)).size,55);
assert.ok(app.includes('localStorage.setItem(stateKey'));
for(const view of ["checklist","roadmap","missables","spoiler"])assert.ok(app.includes('"'+view+'"'),"missing view: "+view);
for(const control of ["data-count","grade-filter","stage-filter","kind-filter","spoiler-toggle"])assert.ok(app.includes(control),"missing UI control: "+control);
assert.ok(data.trophies.filter(t=>t.target!==null).every(t=>Number.isFinite(t.target)));
console.log("test-app.mjs: tracker data and key interactions are present.");
